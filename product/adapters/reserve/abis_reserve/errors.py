from enum import Enum


class ErrorClass(str, Enum):
    DISCOVERY_ERROR = "DISCOVERY_ERROR"
    CAPABILITY_UNAVAILABLE = "CAPABILITY_UNAVAILABLE"
    AUTHENTICATION_REQUIRED = "AUTHENTICATION_REQUIRED"
    AUTHORIZATION_REQUIRED = "AUTHORIZATION_REQUIRED"
    VALIDATION_FAILED = "VALIDATION_FAILED"
    AVAILABILITY_NOT_ESTABLISHED = "AVAILABILITY_NOT_ESTABLISHED"
    SLOT_CONFLICT = "SLOT_CONFLICT"
    PROVIDER_REJECTED = "PROVIDER_REJECTED"
    TRANSPORT_FAILED = "TRANSPORT_FAILED"
    PROVIDER_ACK_NOT_ESTABLISHED = "PROVIDER_ACK_NOT_ESTABLISHED"
    PERSISTENCE_NOT_ESTABLISHED = "PERSISTENCE_NOT_ESTABLISHED"
    BUSINESS_CONFIRMATION_NOT_ESTABLISHED = "BUSINESS_CONFIRMATION_NOT_ESTABLISHED"
    UNSUPPORTED_OPERATION = "UNSUPPORTED_OPERATION"
    UNKNOWN_PROVIDER = "UNKNOWN_PROVIDER"


class ReserveAdapterError(Exception):
    def __init__(
        self,
        error_class: ErrorClass,
        message: str,
        *,
        provider_raw: dict | None = None,
    ):
        super().__init__(message)
        self.error_class = error_class
        self.provider_raw = provider_raw or {}